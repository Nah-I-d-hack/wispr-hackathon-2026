"""[R] Build agent/lines.json from agent/lines_src.json: romanised hi/bn -> native script via Gemini (one-off).

    python -m agent.build_lines            # rebuild everything
The output is stored ASCII-escaped. It keeps the romanised text next to the native text so a human can review it.
"""
from __future__ import annotations

import json
from pathlib import Path

from .llm import generate_json

HERE = Path(__file__).resolve().parent
SYSTEM = ("You convert romanised Hindi or Bengali into correct native script (Devanagari for Hindi, Bengali script "
          "for Bengali). Keep the exact wording and meaning; do not translate, add or drop words. Keep numbers like "
          "112 and 14416 as digits, keep English words commonly used in the language (doctor, BP, sugar, "
          "appointment) in native script as people write them, and keep the {s} and {name} placeholders exactly as written.")


def main() -> None:
    src = json.loads((HERE / "lines_src.json").read_text(encoding="utf-8"))
    keys = [k for k in src if not k.startswith("_")]
    out: dict = {"_note": "[R] Generated by agent/build_lines.py from lines_src.json. Do not edit by hand."}
    for lang, script in (("hi", "Devanagari"), ("bn", "Bengali")):
        res: dict = {}
        todo = list(keys)
        for _ in range(3):  # the model sometimes drops a key; ask again for just those
            items = {k: src[k][lang] for k in todo}
            prompt = (f"Convert each value to {script} script. Return a JSON object with the same keys.\n"
                      + json.dumps(items, ensure_ascii=False))
            got, meta = generate_json(prompt, system=SYSTEM, timeout=60, retries=2)
            res.update({k: v for k, v in got.items() if k in todo and isinstance(v, str) and v.strip()})
            todo = [k for k in keys if k not in res]
            if not todo:
                break
        if todo:
            raise SystemExit(f"{lang}: missing keys {todo}")
        for k in keys:
            for ph in ("{s}", "{name}"):
                if ph in src[k][lang] and ph not in res[k]:
                    raise SystemExit(f"{lang}/{k}: placeholder {ph} lost")
            out.setdefault(k, {"en": src[k]["en"]})
            out[k][lang] = res[k]
            out[k][f"{lang}_roman"] = src[k][lang]
        print(f"{lang}: {len(keys)} lines via {meta['model']}")
    (HERE / "lines.json").write_text(json.dumps(out, ensure_ascii=True, indent=1) + "\n", encoding="utf-8")
    print("wrote agent/lines.json")


if __name__ == "__main__":
    main()
